"""Request ledger with strict mass conservation (methodology §B, plan §7).

Requests are stored as preallocated parallel arrays. The mutually exclusive
statuses are WAITING/BARRED, BACKOFF, ACCESS-IN-PROGRESS, COMPLETED, DROPPED.
COMPLETED and DROPPED are terminal; a request is never silently removed and
never re-enters a queue after a terminal status.

Conservation invariant, checked after every event batch:

    A(t) = C(t) + X(t) + B(t)

where A(t) = cumulative generated by t, C = completed, X = dropped,
B = pending in any non-terminal status (WAITING/BACKOFF/ACCESS-IN-PROGRESS)
among already-generated requests. A deadline miss is a *separate recorded event*,
not a status.
"""
from __future__ import annotations

import numpy as np

from .traffic import Trace

# Status codes
WAITING = 0            # WAITING / BARRED (admission rejected -> still waiting)
BACKOFF = 1
ACCESS = 2             # ACCESS-IN-PROGRESS (preamble succeeded, RA proceeding)
COMPLETED = 3          # terminal
DROPPED = 4            # terminal
STATUS_NAMES = {WAITING: "WAITING", BACKOFF: "BACKOFF", ACCESS: "ACCESS",
                COMPLETED: "COMPLETED", DROPPED: "DROPPED"}
TERMINAL = (COMPLETED, DROPPED)

# Drop-reason codes
DROP_NONE = 0
DROP_RETRY_LIMIT = 1
DROP_OVERFLOW = 2
DROP_EXPIRY = 3
DROP_NAMES = {DROP_NONE: "none", DROP_RETRY_LIMIT: "retry_limit",
              DROP_OVERFLOW: "overflow", DROP_EXPIRY: "expiry_as_drop"}


class ConservationError(AssertionError):
    """Raised when A(t) != C(t) + X(t) + B(t) or another ledger invariant fails."""


class RequestLedger:
    """Mutable per-request state for one run, built from an immutable trace."""

    def __init__(self, trace: Trace):
        n = trace.n_requests
        self.n = n
        self.trace = trace
        # Immutable (copied from trace)
        self.meter_id = trace.meter_id.copy()
        self.arrival_us = trace.arrival_us.copy()
        self.deadline_us = trace.deadline_us.copy()
        self.traffic_class = trace.traffic_class.copy()
        # Mutable state
        self.status = np.full(n, WAITING, dtype=np.int8)
        self.attempts = np.zeros(n, dtype=np.int32)
        self.next_eligible_us = trace.arrival_us.copy()   # eligible at arrival
        self.completion_us = np.full(n, -1, dtype=np.int64)
        self.drop_reason = np.zeros(n, dtype=np.int8)
        self.drop_us = np.full(n, -1, dtype=np.int64)
        self.miss_recorded = np.zeros(n, dtype=bool)
        self.drop_recorded = np.zeros(n, dtype=bool)
        self.on_time = np.zeros(n, dtype=bool)
        self.first_attempt_us = np.full(n, -1, dtype=np.int64)
        # Per-meter concurrency: request id occupying each meter's RA procedure
        self.n_meters = trace.n_meters

    # --- cumulative counts at time t --------------------------------------
    def n_generated(self, t_us: int) -> int:
        return int(np.count_nonzero(self.arrival_us <= t_us))

    def status_counts(self) -> dict[str, int]:
        c = np.bincount(self.status.astype(np.int64), minlength=5)
        return {STATUS_NAMES[i]: int(c[i]) for i in range(5)}

    def pending_count(self, t_us: int) -> int:
        """B(t): generated and in a non-terminal status."""
        generated = self.arrival_us <= t_us
        non_terminal = (self.status == WAITING) | (self.status == BACKOFF) | (self.status == ACCESS)
        return int(np.count_nonzero(generated & non_terminal))

    def true_pending_count(self, t_us: int) -> int:
        """Alias used by the (offline) reward signal B_norm."""
        return self.pending_count(t_us)

    # --- invariants (plan §7) ---------------------------------------------
    def assert_invariants(self, t_us: int) -> None:
        A = self.n_generated(t_us)
        C = int(np.count_nonzero(self.status == COMPLETED))
        X = int(np.count_nonzero(self.status == DROPPED))
        B = self.pending_count(t_us)
        if A != C + X + B:
            raise ConservationError(
                f"conservation failed at t={t_us} us: "
                f"A={A} != C={C}+X={X}+B={B} (={C + X + B})")
        # A terminal request must have a timestamp
        comp = self.status == COMPLETED
        if np.any(comp & (self.completion_us < 0)):
            raise ConservationError("COMPLETED request without completion timestamp")
        drp = self.status == DROPPED
        if np.any(drp & (self.drop_reason == DROP_NONE)):
            raise ConservationError("DROPPED request without a drop reason")
        # No completed request may be marked completed before arrival
        if np.any(comp & (self.completion_us < self.arrival_us)):
            raise ConservationError("completion before arrival")
        # No ungenerated request may be terminal
        ungenerated = self.arrival_us > t_us
        if np.any(ungenerated & ((self.status == COMPLETED) | (self.status == DROPPED))):
            raise ConservationError("terminal status before generation")

    def final_report(self) -> dict:
        counts = self.status_counts()
        return {
            "n_requests": self.n,
            "completed": counts["COMPLETED"],
            "dropped": counts["DROPPED"],
            "pending_waiting": counts["WAITING"],
            "pending_backoff": counts["BACKOFF"],
            "pending_access": counts["ACCESS"],
            "on_time": int(np.count_nonzero(self.on_time)),
            "misses_recorded": int(np.count_nonzero(self.miss_recorded)),
            "drops_retry_limit": int(np.count_nonzero(self.drop_reason == DROP_RETRY_LIMIT)),
            "drops_overflow": int(np.count_nonzero(self.drop_reason == DROP_OVERFLOW)),
            "drops_expiry": int(np.count_nonzero(self.drop_reason == DROP_EXPIRY)),
        }
